def normalize_lang(value) -> str:
    """'es-ES', 'es-419', Locale.spain_spanish… -> 'es'; anything else -> 'en'."""
    return 'es' if str(value or '').lower().startswith('es') else DEFAULT


def lang_for(interaction) -> str:
    """Language for a reply: the user's Discord client locale."""
    return normalize_lang(getattr(interaction, 'locale', None))


def t(lang: str, key: str, **kwargs) -> str:
    """Translated text; falls back to English, then to the key itself."""
    pair = STRINGS.get(key)
    if pair is None:
        return key
    text = pair[1] if lang == 'es' else pair[0]
    return text.format(**kwargs) if kwargs else text


